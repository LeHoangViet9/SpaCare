import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';
import { Spa, User, Control, Day, CashEntry, Audit } from '../src/lib/models';
import { hashPassword } from '../src/lib/password';
import { operate } from '../src/lib/operations';
import { readWorkspace } from '../src/lib/workspace-read';
import { readReport } from '../src/lib/report-read';
import { workspaceQuery } from '../src/lib/workspace-query';
import { spaDay } from '../src/lib/rules';

export async function cashFlowIntegration(extraSpaIds: mongoose.Types.ObjectId[]) {
  const spa=await Spa.create({name:'Synthetic cash summary '+randomUUID()}); extraSpaIds.push(spa._id);
  const scope={spaId:spa._id};
  const owner=await User.create({...scope,name:'Synthetic owner',email:randomUUID()+'@example.test',passwordHash:hashPassword(randomUUID()),role:'OWNER'});
  await Control.create(scope);
  const actor={id:String(owner._id),spaId:String(spa._id),name:owner.name,role:'OWNER' as const,cashier:false};
  const day=spaDay();
  await Day.create({...scope,day,opening:100_000,status:'OPEN'});
  const base={...scope,actorId:owner._id,day,direction:'IN',kind:'INCOME'};
  const original=await CashEntry.create({...base,method:'BANK_TRANSFER',amount:1_750_000});
  const key=randomUUID(), input={id:String(original._id),reason:'Synthetic mistaken receipt'};
  await operate(actor,'reverseCash',input,key); await operate(actor,'reverseCash',input,key);
  for(const amount of [90_000,40_000,60_000,130_000]) await CashEntry.create({...base,method:'CASH',amount});
  for(const amount of [60_000,1_750_000,1_750_000]) await CashEntry.create({...base,method:'BANK_TRANSFER',amount});
  const query=(section:string,extra:Record<string,string>={})=>workspaceQuery(new URLSearchParams({section,from:day,to:day,...extra}));
  const ledgerBefore=await CashEntry.find(scope).sort({_id:1}).lean();
  assert.equal(ledgerBefore.length,9);
  assert.equal(ledgerBefore.find(e=>String(e._id)===String(original._id))!.reversed,true);
  assert.equal(ledgerBefore.filter(e=>e.kind==='REVERSAL'&&String(e.originalId)===String(original._id)).length,1);
  const cash=await readWorkspace(actor,query('cash',{pageSize:'1'}));
  assert.equal(cash.cash.length,1); assert.equal(cash.pages.cash.total,9);
  assert.deepEqual(cash.pages.cash.summary,{incoming:3_880_000,outgoing:0});
  const bank=await readWorkspace(actor,query('cash',{method:'BANK_TRANSFER'}));
  assert.deepEqual(bank.pages.cash.summary,{incoming:3_560_000,outgoing:0});
  const overview=await readWorkspace(actor,query('overview'));
  assert.equal(overview.totals.inflow,3_880_000); assert.equal(overview.totals.outflow,0);
  assert.equal(overview.totals.cashInflow,320_000); assert.equal(overview.totals.bankInflow,3_560_000);
  const report=await readReport(actor,query('reports'));
  assert.equal(report.inflow,3_880_000); assert.equal(report.outflow,0);
  assert.deepEqual(report.days,[{_id:day,incoming:3_880_000,outgoing:0}]);
  const days=await readWorkspace(actor,query('days'));
  assert.equal(days.days[0].liveExpected,420_000); assert.equal(days.days[0].liveBankNet,3_560_000);
  assert.deepEqual(await CashEntry.find(scope).sort({_id:1}).lean(),ledgerBefore,'reads preserve all correction history');
  await CashEntry.create({...base,method:'BANK_TRANSFER',direction:'OUT',kind:'REFUND',amount:250_000});
  const refunded=await readWorkspace(actor,query('cash',{direction:'OUT'}));
  assert.deepEqual(refunded.pages.cash.summary,{incoming:0,outgoing:250_000});
  assert.equal(refunded.pages.cash.total,2,'refund and reversal both remain visible');
  assert.equal((await readReport(actor,query('reports'))).outflow,250_000);
  const other=await Spa.create({name:'Synthetic foreign cash scope'}); extraSpaIds.push(other._id);
  await CashEntry.create({...base,spaId:other._id,method:'CASH',amount:999_999});
  assert.equal((await readWorkspace(actor,query('cash'))).pages.cash.summary.incoming,3_880_000);
  await operate(actor,'closeDay',{day,counted:420_000,expectedPreview:420_000},randomUUID());
  const closed=await Day.findOne(scope);
  assert.equal(closed!.expected,420_000); assert.equal(closed!.bankNet,3_310_000);
  assert.equal(await CashEntry.countDocuments(scope),10);
  assert.equal(await Audit.countDocuments({...scope,action:'reverseCash'}),1);
}
